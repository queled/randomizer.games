const LOCALES = { en: 'en-US', fr: 'fr-FR', es: 'es-ES', de: 'de-DE', it: 'it-IT', pt: 'pt-BR' };

function texts(lang) {
  return TEXTS[lang] || TEXTS.en;
}

function fill(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (match, key) => (values[key] ?? ''));
}

// "26 402 courses": the number in the language's format, the noun in its plural
function count(lang, key, n) {
  const forms = texts(lang)[key];
  const form = new Intl.PluralRules(LOCALES[lang] || 'en-US').select(n) === 'one' ? forms.one : forms.other;
  return fill(form, { n: n.toLocaleString(LOCALES[lang] || 'en-US') });
}

module.exports = { TEXTS, LOCALES, texts, fill, count };
